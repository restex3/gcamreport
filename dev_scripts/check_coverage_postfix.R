# Combine all known-good sources
known_good <- unique(c(all_map_leaves, csv_map_vars, dynamic_vars, computed_vars, ag_production_gains_vars))

# Also consider: variables in template that are ancestors of known-good vars
# (gather_map creates all ancestor hierarchy levels)
ancestor_vars <- character(0)
for(v in known_good) {
  parts <- strsplit(v, '\\|')[[1]]
  for(i in 1:(length(parts)-1)) {
    ancestor_vars <- c(ancestor_vars, paste(parts[1:i], collapse='|'))
  }
}
ancestor_vars <- unique(ancestor_vars)

# Final classification (accounting for updated aliases)
real_independent <- c()
real_with_alias_backup <- c()
alias_only <- c()
missing <- c()

for(v in gains_target) {
  in_known <- v %in% known_good
  in_template <- v %in% template_vars
  in_ancestor <- v %in% ancestor_vars
  is_alias <- v %in% all_alias_targets

  has_real <- in_known || (in_template && in_ancestor)

  if(has_real && !is_alias) {
    real_independent <- c(real_independent, v)
  } else if(has_real && is_alias) {
    real_with_alias_backup <- c(real_with_alias_backup, v)
  } else if(!has_real && is_alias) {
    alias_only <- c(alias_only, v)
  } else {
    missing <- c(missing, v)
  }
}

