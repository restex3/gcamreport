all_map_leaves <- character(0)
for(mn in map_names) {
  full_name <- paste0(mn, '_vGCAMChina8.0')
  obj <- try(get(full_name), silent=TRUE)
  if(!inherits(obj, 'try-error') && 'var' %in% names(obj)) {
    all_map_leaves <- c(all_map_leaves, unique(as.character(obj$var)))
  }
}
